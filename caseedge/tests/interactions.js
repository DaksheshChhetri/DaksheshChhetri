const { chromium } = require('playwright');
const S = process.argv[2], FILE = process.argv[3];
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.route('**/cdnjs.cloudflare.com/**', r => r.fulfill({ path: S + '/vendor/' + (r.request().url().includes('worker') ? 'pdf.worker.min.js' : 'pdf.min.js'), contentType: 'application/javascript' }));
  await p.route('**/fonts.*/**', r => r.abort());
  await p.goto('file://' + FILE); await p.evaluate(() => localStorage.clear()); await p.reload(); await p.waitForTimeout(300);
  const r = {};
  await p.click('#chronoRows tr[data-r="3"]'); await p.waitForTimeout(300);
  r.detail = await p.evaluate(() => !!document.querySelector('#chronoRows tr.detail .enc'));
  await p.locator('#chronoRows tr.detail').screenshot({ path: S + '/shots/f-detail.png' });
  await p.click('#groupBtn'); await p.waitForTimeout(200);
  r.groups = await p.evaluate(() => document.querySelectorAll('#chronoRows tr.grp').length);
  await p.click('#groupBtn');
  r.before = await p.evaluate(() => [document.querySelector('#revCount').textContent, document.querySelector('[data-n="demand"]').textContent]);
  await p.evaluate(() => go('demand')); await p.waitForTimeout(300);
  await p.click('#editor [data-sugact="accept"]'); await p.waitForTimeout(800);
  r.after = await p.evaluate(() => [document.querySelector('#revCount').textContent, document.querySelector('[data-n="demand"]').textContent, document.querySelector('#revNote').textContent, document.querySelectorAll('#reviewRows tr').length]);
  await p.reload(); await p.waitForTimeout(400);
  r.afterReload = await p.evaluate(() => [document.querySelector('#revCount').textContent, document.querySelectorAll('#reviewRows tr').length]);
  await p.evaluate(() => go('review')); await p.waitForTimeout(200);
  await p.click('#reviewRows tr:last-child .golink'); await p.waitForTimeout(600);
  r.jump = await p.evaluate(() => [state.view, !!document.querySelector('#chronoRows tr.row.open[data-r="7"]')]);
  await p.click('#chronoRows tr.row[data-r="7"] .c-src .cite'); await p.waitForTimeout(1500);
  r.pane = await p.evaluate(() => [document.querySelector('#cpDoc').textContent, document.querySelector('#cpSub').textContent, document.querySelector('#stepInfo').textContent]);
  await p.keyboard.press('Escape'); await p.waitForTimeout(400);
  await p.evaluate(() => go('ledger')); await p.click('#ledExpand'); await p.waitForTimeout(200);
  await p.evaluate(() => { document.querySelector('#main').scrollTop = 0 });
  await p.locator('#v-ledger .box').first().screenshot({ path: S + '/shots/f-ledger-open.png' });
  r.errs = errs;
  console.log(JSON.stringify(r));
  await b.close();
})();
